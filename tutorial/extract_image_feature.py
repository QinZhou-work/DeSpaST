def check_white(image):
    """
    Check whether there is enough signal in the input image

    Arg:
    :param image: (matrix) image object

    :return:
        Boolean (true indicating the image is almost completely white)
    """
    image_average = np.average(image)
    image_var = np.var(image)
    return (image_average >= 230) or (image_var <= 100)
    
    
def format_image(image, normalizer, model_device, mag_ratio=1):
    """
    Convert the image format from numpy.array to torch.Tensor

    Arg:
    :param image: (matrix) image object
    :param normalizer: (function) normalization function for the input image
    :param model_device: (object) device on which the torch.Tensor will be allocated
    :param mag_ratio: (float) ratio between model magnitude and image magnitude

    :return:
        image in the torch.Tensor format
    """
    if mag_ratio != 1:
        image = skimage.transform.rescale(image, mag_ratio, preserve_range=True, multichannel=True, 
                                          order=1).astype(np.uint8)
    normalized_image = normalizer(image)
    image_tensor = torch.tensor(np.transpose(normalized_image, (2, 0, 1)).astype(float))
    image_tensor = image_tensor.permute(1, 2, 0).cpu().numpy()
    image_tensor = torch.from_numpy(image_tensor).to(model_device).permute(2, 0, 1)
    image_tensor = torch.stack([image_tensor]).float().to(model_device)
    return image_tensor

def postprocess_prediction(pred, ratio_thresh=0.6):
    """
    There might be several different prediction results over the same region on the image. By this function,
    it only keeps the class with the highest possibility.

    Args:
    :param pred: (list) results generated by the HD-Staining model
    :param ratio_thresh: (0-1 float) threshold used to determine too much overlapping

    :return:
        a dictionary containing processed prediction results without overlapping
    """
    # Transfer model prediction results from torch.Tensor to numpy.array
    masks = pred[0]['masks']
    if masks.size()[0] == 1:
        masks = masks[0].permute(1, 2, 0).detach().cpu().numpy()
    else:
        masks = masks.squeeze().permute(1, 2, 0).detach().cpu().numpy()
    masks = ((masks>=0.5)*1).astype(np.int)
    class_ids = pred[0]['labels']
    class_ids = class_ids.detach().cpu().numpy()
    boxes = pred[0]['boxes']
    boxes = boxes.detach().cpu().numpy()
    scores = pred[0]['scores']
    scores = scores.detach().cpu().numpy()

    # (1) Filter based on area
    to_keep = []
    for i in range(masks.shape[2]):
        pos = np.where(masks[:, :, i])
        if len(pos[0]>0):
            if np.max(pos[1])>np.min(pos[1]) and np.max(pos[0])>np.min(pos[0]):
                to_keep.append(i)
    masks = masks[:, :, to_keep]
    class_ids = class_ids[to_keep]
    boxes = boxes[to_keep]
    scores = scores[to_keep]

    # (2) Filter based on overlaps
    masks_check = masks.copy()
    occlusion = np.ones(np.shape(masks_check)[0:2])
    to_keep = []
    for j in range(masks_check.shape[2]):
        # Remove the mask with tooooo much overlapping with previously detected region
        original_area = np.sum(masks_check[:, :, j])
        masks_check[:, :, j] = masks_check[:, :, j] * occlusion
        new_area = np.sum(masks_check[:, :, j])
        if new_area > 0 and new_area / original_area > ratio_thresh:
            to_keep.append(True)
            occlusion = np.logical_and(occlusion, np.logical_not(masks_check[:, :, j]))
        else:
            to_keep.append(False)
    masks = masks[:, :, to_keep]
    class_ids = class_ids[to_keep]
    boxes = boxes[to_keep]
    scores = scores[to_keep]
    
    # Collect processed model prediction results in a dictionary
    processed_pred = {'masks': masks, 
                      'class_ids': class_ids,
                      'boxes': boxes,
                      'scores': scores}
    return processed_pred

def get_box_features(model, features, proposals, patch_size=(512, 512)):
    """
    Extract box features from the HD-Staining model

    Args:
    :param model: the HD-Staining model for nuclei segmentation and classification
    :param features: (collections.OrderedDict) features from the backbone of the HD-Staining model
    :param proposals: (list) proposals from the rpn of the HD-Staining model
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)

    :return:
        - box_features
        - pred_boxes
        - pred_scores
    """
    # Get box_features for each proposal
    box_features = model.netG.roi_heads.box_roi_pool(features, proposals, [patch_size])
    box_features = model.netG.roi_heads.box_head(box_features)
    
    # Get pred_boxes and corresponding pred_scores for each proposal
    class_logits, box_regression = model.netG.roi_heads.box_predictor(box_features)
    pred_boxes = model.netG.roi_heads.box_coder.decode(box_regression, proposals)
    pred_boxes = box_ops.clip_boxes_to_image(pred_boxes, patch_size)
    pred_boxes = pred_boxes.reshape(-1, 4)
    pred_boxes = pred_boxes.detach().cpu().numpy()
    pred_scores = torch.nn.functional.softmax(class_logits, -1)
    pred_scores = pred_scores.reshape(-1)
    pred_scores = pred_scores.detach().cpu().numpy()
    return box_features, pred_boxes, pred_scores

def get_mask_features(model, processed_pred, features, patch_size=(512, 512)):
    """
    Extract mask features from the HD-Staining model

    Args:
    :param model: the HD-Staining model for nuclei segmentation and classification
    :param processed_pred: (dict) processed prediction results without overlapping
    :param features: (collections.OrderedDict) features from the backbone of the HD-Staining model
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)

    :return:
        mask_features for each detected nucleus
    """
    boxes = processed_pred['boxes']
    mask_proposals = [torch.tensor(boxes).to(model.netG.device)]
    mask_features = model.netG.roi_heads.mask_roi_pool(features, mask_proposals, [patch_size])
    mask_features = model.netG.roi_heads.mask_head(mask_features)
    return mask_features

def get_nucleus_features(processed_pred, model_classes, box_features, pred_boxes, pred_scores, mask_features):
    """
    Collect basic features, box features and mask features of each detected nucleus

    Args:
    :param processed_pred: (dict) processed prediction results without overlapping
    :param model_classes: (list) classes setting of the HD-Staining model
    :param box_features: (torch.Tensor) box features for each proposal from the rpn of the HD-Staining model
    :param pred_boxes: (numpy.array) predicted boxes for each proposal from the rpn of the HD-Staining model
    :param pred_scores: (numpy.array) predicted scores for each proposal from the rpn of the HD-Staining model
    :param mask_features: (torch.Tensor) mask features for each detected nucleus

    :return:
        a form containing the feature information of each nucleus on the whole patch
    """
    # Extract results of different categories from processed_pred
    masks = processed_pred['masks']
    class_ids = processed_pred['class_ids']
    boxes = processed_pred['boxes']
    scores = processed_pred['scores']
    
    # Define the column_names of the result form
    column_names = ['nucleus_id', 'nucleus_class', 'centroid_x0', 'centroid_y0', 'area', 'convex_area', 'eccentricity',
                    'extent', 'filled_area', 'major_axis_length', 'minor_axis_length', 'orientation', 'perimeter',
                    'solidity', 'bbox_x1', 'bbox_y1', 'bbox_x2', 'bbox_y2', 'probability', 'probability_vector']
    for i in range(0, box_features.size()[1]):
        column_name = 'box_feature_' + str(i+1)
        column_names.append(column_name)
    for i in range(0, mask_features.size()[1]):
        column_name = 'mask_feature_' + str(i+1)
        column_names.append(column_name)
    
    # Collect the feature information of each nucleus in the form
    nucleus_form = []
    for target_index in range(0, len(class_ids)):
        # Get the identity information of the target nucleus
        nucleus_id = str(target_index)
        nucleus_class = model_classes[class_ids[target_index]-1]
        target_basic_features = [nucleus_id, nucleus_class]
        # Get the morphology features of the target nucleus
        target_mask = masks[..., target_index]
        target_properties = skimage.measure.regionprops(target_mask)[0]
        target_basic_features.extend([target_properties.centroid[1], target_properties.centroid[0], 
                                      target_properties.area, target_properties.convex_area,
                                      target_properties.eccentricity, target_properties.extent, 
                                      target_properties.filled_area, target_properties.major_axis_length, 
                                      target_properties.minor_axis_length, target_properties.orientation, 
                                      target_properties.perimeter, target_properties.solidity])
        # Get the bbox information of the target nucleus
        target_basic_features.extend(boxes[target_index].tolist())
        # Get the probability information of the target nucleus
        target_basic_features.append(scores[target_index])
        # Get the box features of the target nucleus
        box_list = [i for i, val in enumerate(pred_boxes) if np.all(val==boxes[target_index])]
        score_list = np.where(pred_scores==scores[target_index])[0].tolist()
        reshaped_index = list(set(box_list).intersection(set(score_list)))[0]
        proposal_index = reshaped_index // (len(model_classes)+1)
        target_basic_features.append(pred_scores[(proposal_index)*(len(model_classes)+1):
                                                 (proposal_index+1)*(len(model_classes)+1)])
        target_box_features = box_features[proposal_index].detach().cpu().numpy().tolist()
        # Get the mask features of the target nucleus
        target_mask_features = mask_features[target_index]
        target_mask_features = torch.nn.AvgPool2d(target_mask_features.size()[-1])(target_mask_features)
        target_mask_features = target_mask_features.detach().cpu().numpy().reshape(-1).tolist()
        # Gather all features of the target nucleus
        target_nucleus_form = target_basic_features + target_box_features + target_mask_features
        nucleus_form.append(target_nucleus_form)
    nucleus_form = pd.DataFrame(data=nucleus_form, columns=column_names)
    return nucleus_form

def select_central_nucleus(nucleus_form, patch_size=(512, 512), patch_rim=0):
    """
    Select the nucleus in the main region of the patch

    Args:
    :param nucleus_form: (dataframe) a form containing the feature information of each nucleus on the whole patch
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)
    :param patch_rim: (int) width of the rim around the main region of the patch

    :return:
        a form containing the feature information of each nucleus in the main region of the patch
    """
    central_nucleus_form = nucleus_form.copy()
    for target_index in range(0, len(nucleus_form)):
        centroid_y0 = nucleus_form['centroid_y0'].values[target_index]
        centroid_x0 = nucleus_form['centroid_x0'].values[target_index]
        if patch_rim <= centroid_y0 < (patch_size[0]-patch_rim) and patch_rim <= centroid_x0 < (patch_size[1]-patch_rim):
            central_nucleus_form = central_nucleus_form
        else:
            central_nucleus_form = central_nucleus_form.drop(nucleus_form.index[target_index])
    central_nucleus_form = central_nucleus_form.reset_index(drop=True)
    return central_nucleus_form

def modify_nucleus_form(nucleus_form, patch_name='', mag_ratio=1):
    """
    Modify nucleus id and centroid location information

    Args:
    :param nucleus_form: (dataframe) a form containing the feature information of each nucleus in the main region of 
    the patch
    :param patch_name: (string) name containing location information of the patch to the whole slide (the number in
    front of 'x' indicating height location and number behind 'x' indicating width location)
    :param mag_ratio: (float) ratio between model magnitude and image magnitude

    :return:
        a form containing the feature information of each nucleus in the main region of the patch 
        (location information is the location on the original whole slide)
    """
    # Get location information of the target patch to the whole slide
    if len(patch_name) != 0:
        patch_id = patch_name + '_'
        patch_location_h = int(re.findall('[0-9]+(?=x)', patch_name)[-1])
        patch_location_w = int(re.findall('(?<=x)[0-9]+', patch_name)[-1])
        patch_location = (patch_location_h, patch_location_w)
    else:
        patch_id = patch_name
        patch_location = (0, 0)
    
    # Update information for each nucleus
    modified_nucleus_form = nucleus_form.copy()
    for target_index in range(0, len(nucleus_form)):
        # Update nucleus_id of the target nucleus
        nucleus_id = str(target_index+1)
        new_nucleus_id = patch_id + nucleus_id
        modified_nucleus_form.at[target_index, 'nucleus_id'] = new_nucleus_id
        # Update centroid information of the target nucleus
        centroid_x0 = nucleus_form['centroid_x0'].values[target_index]
        new_centroid_x0 = patch_location[1] + int(centroid_x0/mag_ratio)
        modified_nucleus_form.at[target_index, 'centroid_x0'] = new_centroid_x0
        centroid_y0 = nucleus_form['centroid_y0'].values[target_index]
        new_centroid_y0 = patch_location[0] + int(centroid_y0/mag_ratio)
        modified_nucleus_form.at[target_index, 'centroid_y0'] = new_centroid_y0
    # Change the type of centroid columns
    modified_nucleus_form = modified_nucleus_form.astype({'centroid_x0': int, 'centroid_y0': int})
    return modified_nucleus_form

def get_predicted_mask(processed_pred, model_classes, rgb_markers, bg_color=[255, 255, 255]):
    """
    Generate a colorful mask based on processed prediction results

    Args:
    :param processed_pred: (dict) processed prediction results without overlapping
    :param model_classes: (list) classes setting of the HD-Staining model
    :param rgb_markers: (dict) colors setting of the HD-Staining model (except background)
    :param bg_color: (list) color setting for background

    :return
        a mask containing all classes of nuclei labelled by different colors
    """
    masks = processed_pred['masks']
    class_ids = processed_pred['class_ids']
    predicted_mask = np.zeros((masks.shape[0], masks.shape[1], 3), dtype=np.uint8)
    predicted_mask[:, :] = bg_color  # Background
    for target_index in range(masks.shape[2]):
        predicted_mask[masks[:, :, target_index]==1] = rgb_markers[model_classes[class_ids[target_index]-1]]
    return predicted_mask

