def apply_hd_staining_to_patch(model, model_parameters, dataset_config, patch_image, patch_name='', model_mag=40, 
                               image_mag=40, patch_rim=0, save_form=False, plot_image=False, save_image=False, 
                               save_dir=''):
    """
    Apply the HD-Staining model to a single patch

    Args:
    :param model: the HD-Staining model for nuclei segmentation and classification
    :param model_parameters: (class) parameters required for the HD-Staining model
    :param dataset_config: (dict) dataset config for inference
    :param patch_image: (numpy matrix) matrix of the original patch image
    :param patch_name: (string) name containing location information of the patch to the whole slide (the number in
    front of 'x' indicating height location and number behind 'x' indicating width location)
    :param model_mag: (int) magnitude of the HD-Staining model
    :param image_mag: (int) magnitude of the original patch image
    :param patch_rim: (int) width of the rim around the main region of the patch
    :param save_form: (bool, optional) if True, save the form about nucleus information, default is False
    :param plot_image: (bool, optional) if True, plot the result images, default is False
    :param save_image: (bool, optional) if True, save the result images, default is False
    :param save_dir: (string) the folder to save analysis results

    :return
        a form containing the feature information of each nucleus in the main region of the patch
        result images:
        - original image
        - model input
        - predicted mask
    
    :raise:
        IOError: an error occurs if patch_rim is not in the range of [0, half of patch height/width)
    """
    # Get size information of patch_image
    patch_size = patch_image.shape[0:2]
    
    # Check the value of patch_rim
    if not (0 <= patch_rim < (0.5*patch_size[0]) and 0 <= patch_rim < (0.5*patch_size[1])):
        raise IOError('Please put appropriate number in the argument of patch_rim [0, half of patch height/width)')
    
    # Calculate the ratio between model_mag and image_mag
    mag_ratio = model_mag / image_mag
    model_input_rim = int(patch_rim*mag_ratio)
    
    # Convert the image format from numpy.array to torch.Tensor
    image_tensor = format_image(patch_image, dataset_config['normalizer'], model.netG.device, mag_ratio)
    
    # Run detection
    _, pred = model.netG(image_tensor, is_20x=False)
    
    # Post-process
    processed_pred = postprocess_prediction(pred, ratio_thresh=0.6)
    
    # Check whether there is any nucleus on the target patch
    if len(processed_pred['class_ids']) == 0:
        if len(patch_name) == 0:
            print('Stop analyzing this patch because of no nucleus on this patch')
        else:
            print('Stop analyzing ({}) because of no nucleus on this patch'.format(patch_name))
        return[]
    
    # Get features and proposals from the HD-Staining model
    image_imagelist, _ = model.netG.transform(image_tensor, None)
    model_input_size = image_imagelist.image_sizes[0]
    # Shift resnet 1st conv2d to stride = 2
    model.netG.backbone.body.conv1 = model.netG.conv1_40x
    model.netG.backbone.to(model.netG.device)
    features = model.netG.backbone(image_imagelist.tensors)
    proposals, _ = model.netG.rpn(image_imagelist, features, None)
    
    # Get box features from the HD-Staining model
    box_features, pred_boxes, pred_scores = get_box_features(model, features, proposals, model_input_size)
    
    # Get mask features from the HD-Staining model
    mask_features = get_mask_features(model, processed_pred, features, model_input_size)
    
    # Gather nucleus information in the form
    nucleus_form = get_nucleus_features(processed_pred, model_parameters.classes, box_features, pred_boxes, 
                                        pred_scores, mask_features)
    nucleus_form = select_central_nucleus(nucleus_form, model_input_size, model_input_rim)
    nucleus_form = modify_nucleus_form(nucleus_form, patch_name, mag_ratio)
    
    if save_form:
        if len(patch_name) == 0:
            form_name = 'nucleus_information_model{}_image{}.csv'.format(model_mag, image_mag)
        else:
            form_name = '({})_information_model{}_image{}.csv'.format(patch_name, model_mag, image_mag)
        form_path = os.path.join(save_dir, form_name)
        nucleus_form.to_csv(form_path, index=False)
    
    if plot_image or save_image:
        displayed_model_input = uimg_d.RGB_Normalizer(mean=model_parameters.stain_mean, std=model_parameters.stain_std, 
                                                      inverse=True)(image_tensor[0].permute(1, 2, 0).detach().cpu().numpy())
        predicted_mask = get_predicted_mask(processed_pred, model_parameters.classes, model_parameters.rgb_markers, 
                                            bg_color=[255, 255, 255])
    
    if plot_image:
        plot_result_images(patch_image, displayed_model_input, predicted_mask, model_mag, image_mag, model_input_rim)
    
    if save_image:
        save_result_images(patch_image, displayed_model_input, predicted_mask, model_mag, image_mag, model_input_rim, 
                           patch_name, save_dir)
    return nucleus_form

def get_continuous_patch_parameters(slide, region_parameters, patch_size=(512, 512), patch_rim=0):
    """
    Gather location and size information of each patch by continuous method

    Args:
    :param slide: (array) image object
    :param region_parameters: (tuple) location information (min_row, min_col, max_row, max_col) of the main region of
    the slide
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)
    :param patch_rim: (int) width of the rim around the main region of the patch

    :return:
        a list containing location and size information of all patches generated from the main region of the slide
        (location information is the location on the original whole slide)
    """
    # Get parameters of the main region of the slide and also single patch
    region_height = region_parameters[2] - region_parameters[0] - (2*patch_rim)
    region_width = region_parameters[3] - region_parameters[1] - (2*patch_rim)
    patch_height, patch_width = patch_size
    patch_region_height = patch_height - (2*patch_rim)
    patch_region_width = patch_width - (2*patch_rim)

    # Get parameters to extract the target patch from the slide
    patch_parameters = []
    for h in range(0, region_height, patch_region_height):
        if region_height - h < patch_region_height:
            target_height = region_height % patch_region_height + (2*patch_rim)
        else:
            target_height = patch_height
        for w in range(0, region_width, patch_region_width):
            if region_width - w < patch_region_width:
                target_width = region_width % patch_region_width + (2*patch_rim)
            else:
                target_width = patch_width
            # Transfer the location on the modified main region of the slide to the location on the original whole slide
            target_patch_location = (h+region_parameters[0], w+region_parameters[1])
            target_patch_size = (target_height, target_width)
            # Check whether there is enough signal in the target patch
            target_patch = slide[target_patch_location[0]:(target_patch_location[0]+target_patch_size[0]), 
                                 target_patch_location[1]:(target_patch_location[1]+target_patch_size[1]), :]
            if check_white(target_patch):
                continue
            patch_parameters.append((target_patch_location, target_patch_size))
    return patch_parameters

def choose_random_pixel(region_parameters, patch_size=(512, 512)):
    """
    Randomly choose one pixel in the input matrix

    Args:
    :param region_parameters: (tuple) location information (min_row, min_col, max_row, max_col) of the main region of
    the slide
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)

    :return
        a tuple containing location information of the selected pixel (location information is the location on the
        modified main region of the slide)
    """
    region_height = region_parameters[2] - region_parameters[0]
    region_width = region_parameters[3] - region_parameters[1]
    selected_h = np.random.randint(0, region_height-patch_size[0])
    selected_w = np.random.randint(0, region_width-patch_size[1])
    selected_location = (selected_h, selected_w)
    return selected_location

def get_random_patch_parameters(slide, region_parameters, patch_size=(512, 512), patch_num=0, plot_mask=False):
    """
    Gather location and size information of each patch by random method

    Args:
    :param slide: (array) image object
    :param region_parameters: (tuple) location information (min_row, min_col, max_row, max_col) of the main region of
    the slide
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)
    :param patch_num: (int) the number of patches to be randomly extracted
    :param plot_mask: (bool, optional) if True, plot the extracted mask, default is False

    :return:
        a list containing location and size information of patches randomly selected from the main region of the slide
        (location information is the location on the original whole slide)
    """
    if plot_mask:
        # Draw an empty mask
        mask = np.zeros(slide.shape[0:2], dtype=np.uint8)
        mask[region_parameters[0]:region_parameters[2],
             region_parameters[1]:region_parameters[3]] = 255

    patch_parameters = []
    effective_loop = 0
    while effective_loop < patch_num:
        # Randomly choose a pixel as the top-left point of the patch
        selected_patch_location = choose_random_pixel(region_parameters, patch_size)
        # Transfer the location on the modified main region of the slide to the location on the original whole slide
        selected_patch_location = (selected_patch_location[0]+region_parameters[0], 
                                   selected_patch_location[1]+region_parameters[1])
        # Check whether there is enough signal in the selected patch
        selected_patch = slide[selected_patch_location[0]:(selected_patch_location[0]+patch_size[0]), 
                               selected_patch_location[1]:(selected_patch_location[1]+patch_size[1]), :]
        if check_white(selected_patch):
            continue
        effective_loop += 1
        patch_parameters.append((selected_patch_location, patch_size))
        # Label corresponding region in the mask
        if plot_mask:
            mask[selected_patch_location[0]:(selected_patch_location[0]+patch_size[0]),
                 selected_patch_location[1]:(selected_patch_location[1]+patch_size[1])] = 0
    
    if plot_mask:
        fig, axes = plt.subplots(1, 2, figsize=(12, 12))
        ax = axes.ravel()
        ax[0].imshow(slide)
        ax[0].set_title('Slide')
        ax[1].imshow(mask)
        ax[1].set_title('Mask')
        plt.show(block=True)
        plt.close()
    return patch_parameters

def get_single_patch(slide, patch_parameters, slide_id=''):
    """
    Extract one patch from the original whole slide according to its location and size information

    Args:
    :param slide: (array) image object
    :param patch_parameters: (tuple) location and size information of the target patch (the first element indicating
    patch location and the second element indicating patch size)
    :param slide_id: (string) name of the slide

    :return:
        - patch_image: the image of the target patch
        - patch_name: the name of the target patch in the format of [(slide_id)]_[h_location]x[w_location]
    """
    # Get the image of the target patch
    patch_location = patch_parameters[0]
    patch_size = patch_parameters[1]
    patch_image = slide[patch_location[0]:(patch_location[0]+patch_size[0]), 
                        patch_location[1]:(patch_location[1]+patch_size[1]), :]
    
    # Determine the name of the target patch
    if len(slide_id) != 0:
        patch_name = '_'.join(['('+slide_id+')', 'x'.join([str(patch_location[0]), str(patch_location[1])])])
    else:
        patch_name = 'x'.join([str(patch_location[0]), str(patch_location[1])])
    return patch_image, patch_name

def apply_hd_staining_to_slide(model, model_parameters, dataset_config, slide, slide_id, model_mag=40, 
                               image_mag=40, region_parameters=(0, 0, 0, 0), patch_method='continuous',
                               patch_size=(512, 512), patch_rim=0,  patch_num=0, save_form=False, 
                               save_image=False, save_patch_num=0, save_dir=''):
    """
    Apply the HD-Staining model to a slide

    Args:
    :param model: the HD-Staining model for nuclei segmentation and classification
    :param model_parameters: (class) parameters required for the HD-Staining model
    :param dataset_config: (dict) dataset config for inference
    :param slide: (array) image object
    :param slide_id: (string) name of the slide
    :param model_mag: (int) magnitude of the HD-Staining model
    :param image_mag: (int) magnitude of the original patch image
    :param region_parameters: (tuple) location information (min_row, min_col, max_row, max_col) of the main region of
    the slide
    :param patch_method: method to generate patches ('continuous' or 'random')
    :param patch_size: (tuple) a tuple containing two numbers (the first one indicating height and the second one
    indicating width of the patch)
    :param patch_rim: (int) width of the rim around the main region of the patch
    :param patch_num: (int) if patch_method is 'random', the number of patches to be randomly extracted
    :param save_form: (bool, optional) if True, save the nucleus information form of all analyzed patches,
    default is False
    :param save_image: (bool, optional) if True, save the result images, default is False
    :param save_patch_num: (int) if save_image is True, the number of patches whose result images to be saved
    :param save_dir: (string) the folder to save analysis results

    :return
        a form containing the feature information of each nucleus in the main region of all analyzed patches
        result images:
        - original image
        - model input
        - predicted mask
    
    :raise:
        IOError: an error occurs if the patch_method is not well defined.
        IOError: an error occurs if patch_method is 'random' but patch_num is less than one.
        IOError: an error occurs if save_image is True and save_patch_num is less than one.
    """
    # Create an empty folder to save analysis results for the target slide
    if save_image or save_form:
        save_dir = os.path.join(save_dir, slide_id)
        if not os.path.exists(save_dir):
            os.makedirs(save_dir)
    
    # Get patch_parameters
    if patch_method == 'continuous':
        patch_parameters = get_continuous_patch_parameters(slide, region_parameters, patch_size, patch_rim)
    elif patch_method == 'random':
        if patch_num < 1:
            raise IOError('Please put appropriate number in the argument of patch_num (current number is too small)')
        else:
            patch_parameters = get_random_patch_parameters(slide, region_parameters, patch_size, patch_num, 
                                                           plot_mask=True)
    else:
        raise IOError('Please specify the method to generate patches: continuous or random')
        
    # Randomly select the patches whose results to be saved
    total_patch_num = len(patch_parameters)
    print('Total number of patches to be analyzed: {}'.format(total_patch_num))
    if save_image:
        if save_patch_num < 1:
            raise IOError('Please put appropriate number in the argument of save_patch_num (current number is too small)')
        elif save_patch_num >= total_patch_num:
            print('Save the result images of all patches')
            selected_save_index = np.array(range(0, total_patch_num))
        else:
            print('Save the result images of {} patches'.format(save_patch_num))
            selected_save_index = np.random.choice(range(0, total_patch_num), size=save_patch_num, replace=False)
    
    # Apply analysis to every single patch
    final_form = pd.DataFrame()
    for target_index in range(0, total_patch_num):
        patch_image, patch_name = get_single_patch(slide, patch_parameters[target_index], slide_id)
        modified_patch_image = np.zeros((patch_size[0], patch_size[1], 3), dtype=np.uint8)
        modified_patch_image[:, :, :] = 255
        modified_patch_image[0:patch_image.shape[0], 0:patch_image.shape[1], :] = patch_image
        print('----------------------------------------------------------------------------')
        print('Start to analyze: {}'.format(patch_name))
        if save_image:
            if target_index in selected_save_index:
                print('Save the result images of this patch')
                patch_form = apply_hd_staining_to_patch(model, model_parameters, dataset_config, modified_patch_image, 
                                                        patch_name, model_mag, image_mag, patch_rim, save_form=False, 
                                                        plot_image=False, save_image=True, save_dir=save_dir)
            else:
                patch_form = apply_hd_staining_to_patch(model, model_parameters, dataset_config, modified_patch_image, 
                                                        patch_name, model_mag, image_mag, patch_rim, save_form=False, 
                                                        plot_image=False, save_image=False, save_dir=save_dir)
        else:
            patch_form = apply_hd_staining_to_patch(model, model_parameters, dataset_config, modified_patch_image, 
                                                    patch_name, model_mag, image_mag, patch_rim, save_form=False, 
                                                    plot_image=False, save_image=False, save_dir=save_dir)
        # Store nucleus information of the target patch
        if len(patch_form) != 0:
            if len(final_form) == 0:
                final_form = patch_form
            else:
                final_form = final_form.append(patch_form, ignore_index=True)
    
    if save_form:
        form_name = '({})_information_model{}_image{}.csv'.format(slide_id, model_mag, image_mag)
        form_path = os.path.join(save_dir, form_name)
        final_form.to_csv(form_path, index=False)
    return final_form



